//! Explicit state, independent counter oracle, launch tails, and chunk replay.
use super::*;
use ferrum_execution::component::{
    CompiledTensorComponent, ComponentWeightSource, TensorComponentPolicy,
};
use ferrum_models::normal_noise::{NormalNoiseConfig, NormalNoiseFamily};

fn words(mut counter: [u32; 4], key: [u32; 2]) -> [u32; 4] {
    for round in 0..10_u32 {
        let a = u64::from(counter[0]) * 0xD2511F53;
        let b = u64::from(counter[2]) * 0xCD9E8D57;
        counter = [
            (b >> 32) as u32 ^ counter[1] ^ key[0].wrapping_add(round.wrapping_mul(0x9E3779B9)),
            b as u32,
            (a >> 32) as u32 ^ counter[3] ^ key[1].wrapping_add(round.wrapping_mul(0xBB67AE85)),
            a as u32,
        ];
    }
    counter
}
fn known_answers() {
    // Published Random123 Philox4x32-10 vectors, not generated by this oracle:
    // https://github.com/DEShawResearch/random123/blob/main/tests/kat_vectors
    assert_eq!(
        words([0; 4], [0; 2]),
        [0x6627e8d5, 0xe169c58d, 0xbc57ac4c, 0x9b00dbd8]
    );
    assert_eq!(
        words([u32::MAX; 4], [u32::MAX; 2]),
        [0x408f276d, 0x41c83b0e, 0xa20bc7c6, 0x6d5451fd]
    );
    assert_eq!(
        words(
            [0x243f6a88, 0x85a308d3, 0x13198a2e, 0x03707344],
            [0xa4093822, 0x299f31d0]
        ),
        [0xd16cfe09, 0x94fdcceb, 0x5001e420, 0x24126ea1]
    );
}
fn neighbours(value: f32) -> (f32, f32) {
    let (mut lo, mut hi) = (value, value);
    // MSL 4.1 table 8.1: log/sin/cos <=4 ULP, plus reference rounding.
    for _ in 0..5 {
        lo = lo.next_down();
        hi = hi.next_up();
    }
    (lo, hi)
}
fn check(state: PhiloxSeedOffset, actual: &[f32]) {
    let mut previous_block = u128::MAX;
    let mut bits = [0; 4];
    for (i, &got) in actual.iter().enumerate() {
        // u128 deliberately differs from the shader's divide-before-add scheme.
        let ordinal = u128::from(state.offset()) + i as u128;
        let block = ordinal / 4;
        if block != previous_block {
            bits = words(
                [block as u32, (block >> 32) as u32, 0, 0],
                [state.seed() as u32, (state.seed() >> 32) as u32],
            );
            previous_block = block;
        }
        let lane = (ordinal % 4) as usize;
        let pair = lane / 2 * 2;
        let uniform = |word: u32| ((word >> 9) as f32 + 0.5) * 2_f32.powi(-23);
        let (log_lo, log_hi) = neighbours(libm::log(uniform(bits[pair]) as f64) as f32);
        let radius = [
            libm::sqrtf(-2.0 * log_hi).next_down(),
            libm::sqrtf(-2.0 * log_lo).next_up(),
        ];
        let angle = std::f32::consts::TAU * uniform(bits[pair + 1]);
        let center = if lane % 2 == 0 {
            libm::cos(angle as f64)
        } else {
            libm::sin(angle as f64)
        };
        let (lo, hi) = neighbours(center as f32);
        let trig = [lo.max(-1.0), hi.min(1.0)];
        let products = [
            radius[0] * trig[0],
            radius[0] * trig[1],
            radius[1] * trig[0],
            radius[1] * trig[1],
        ];
        let lo = rounds(products.into_iter().fold(f32::INFINITY, f32::min));
        let hi = rounds(products.into_iter().fold(f32::NEG_INFINITY, f32::max));
        assert!(
            got.is_finite() && got >= lo && got <= hi,
            "noise seed={} offset={} i={i}: {got} outside [{lo},{hi}]",
            state.seed(),
            state.offset()
        );
    }
}

pub(super) fn verify(
    runtime: &Arc<MetalDeviceRuntime>,
    registry: &OperationRuntimeRegistry<MetalDeviceRuntime>,
    catalog: &CapabilityCatalog,
    host: &HostMemoryAccount,
) {
    known_answers();
    let policy = TensorComponentPolicy::new(
        CAPACITY,
        runtime
            .descriptor()
            .dynamic_storage_profiles
            .iter()
            .copied()
            .collect(),
    )
    .unwrap();
    let execute = |count, state: PhiloxSeedOffset| {
        let config = NormalNoiseConfig::new(1, 1, count).unwrap();
        let profile = MetalTensorOperation::PhiloxNormal.profile();
        let prepared = TypedFamilyRegistration::new(NormalNoiseFamily::new(profile).unwrap())
            .prepare_with_profile(&serde_json::to_value(&config).unwrap(), &id(profile))
            .unwrap();
        let component = CompiledTensorComponent::compile(
            prepared,
            registry,
            catalog,
            &policy,
            &WeightMaterializerRegistry::identity_only().unwrap(),
            &config.compile_options().unwrap(),
        )
        .unwrap();
        let mut session = component
            .initialize(
                runtime.clone(),
                host.clone(),
                ComponentWeightSource::None,
                transforms::initialization("metal.noise"),
            )
            .unwrap();
        let mut bytes = host
            .allocate_zeroed(HostMemoryClass::InputPreprocess, 16)
            .unwrap();
        bytes.as_mut().copy_from_slice(&state.little_endian_bytes());
        let state_tensor = ManagedHostTensor::new(
            id(NormalNoiseFamily::STATE_ID),
            NormalNoiseConfig::state_tensor().unwrap(),
            bytes.freeze(),
        )
        .unwrap();
        let mut previous: Option<ManagedHostBytes> = None;
        for repeat in 0..2 {
            let outputs = session
                .execute(
                    id(format!("run.metal.noise.{repeat}")),
                    id(format!("request.metal.noise.{repeat}")),
                    vec![state_tensor.clone()],
                )
                .unwrap();
            assert_eq!(outputs.len(), 1);
            assert_eq!(outputs[0].tensor(), &config.output_tensor().unwrap());
            assert_eq!(state_tensor.bytes().bytes(), &state.little_endian_bytes());
            let output = outputs[0].bytes();
            check(state, &transforms::decode(output.bytes()));
            if let Some(previous) = &previous {
                assert_eq!(previous.bytes(), output.bytes());
            }
            previous = Some(output.clone());
        }
        assert!(matches!(
            session.try_release_idle_dynamic_backing().unwrap(),
            IdleDynamicReleaseOutcome::Released(_)
        ));
        assert!(matches!(
            session
                .close()
                .unwrap_or_else(|e| panic!("close noise: {:?}", e.failure())),
            PlanRuntimeCloseOutcome::Closed(_)
        ));
        let result = transforms::decode(previous.as_ref().unwrap().bytes());
        drop(previous);
        drop(state_tensor);
        assert_eq!(host.usage().unwrap().committed_bytes(), 0);
        result
    };
    for count in [1, 3, 4, 5, 257, 262147] {
        execute(count, PhiloxSeedOffset::fresh(42));
    }
    for seed in [0, 1, 1 << 32, 1 << 63, u64::MAX] {
        for offset in [0, 1, 2, 3, (1 << 34) - 1, u64::MAX - 2, u64::MAX] {
            execute(65, PhiloxSeedOffset::new(seed, offset));
        }
    }
    for offset in [0, (1 << 34) - 3, u64::MAX - 32] {
        let full = execute(65, PhiloxSeedOffset::new(17, offset));
        let slice = execute(19, PhiloxSeedOffset::new(17, offset + 13));
        assert_eq!(slice, full[13..32]);
        assert_eq!(execute(7, PhiloxSeedOffset::new(17, offset)), full[..7]);
    }
    let low = execute(65, PhiloxSeedOffset::fresh(7));
    let high = execute(65, PhiloxSeedOffset::fresh(7 | (1 << 40)));
    assert_ne!(low, high);
    eprintln!("Metal Philox: published counter vectors, all seed/offset bits, tails/grid stride, repeat, chunk replay and retirement passed");
}
